// Dynamic Vite glob import for all 66 books in src/data/books/*.json
const bookLoaders = import.meta.glob<{ default: Question[] }>('./books/*.json');

// Memory cache for instant access
const bookCache = new Map<string, Question[]>();

// Pre-populate Genesis into cache
bookCache.set('genesis', GENESIS_QUESTIONS);

/**
 * Loads questions for any of the 66 books on-demand from its split JSON bundle.
 * Caches in memory for instant subsequent lookups.
 */
export async function loadQuestionsForBook(bookId: string): Promise<Question[]> {
  const normalizedId = bookId.toLowerCase().trim();
  if (bookCache.has(normalizedId)) {
    return bookCache.get(normalizedId)!;
  }

  const path = `./books/${normalizedId}.json`;
  const loader = bookLoaders[path];
  if (loader) {
    try {
      const module = await loader();
      const raw = (module.default || module) as Question[];
      bookCache.set(normalizedId, raw);
      return raw;
    } catch (err) {
      console.error(`Failed to load book questions: ${bookId}`, err);
    }
  }

  // Fallback to core questions for this book
  const fallback = CORE_QUESTIONS.filter((q) => q.bookId === normalizedId);
  return fallback;
}

export function getCachedQuestionsForBook(bookId: string): Question[] | undefined {
  return bookCache.get(bookId.toLowerCase().trim());
}

/**
 * Asynchronously loads questions for a chapter or full book quiz, ensuring the JSON chunk is ready.
 */
export async function getQuestionsForBookAsync(bookId: string, chapter?: number): Promise<Question[]> {
  const allBookQuestions = await loadQuestionsForBook(bookId);

  if (chapter) {
    const chapterQuestions = allBookQuestions.filter((q) => q.chapter === chapter);
    if (chapterQuestions.length > 0) {
      return chapterQuestions.map(shuffleQuestionOptions);
    }
  }

  if (allBookQuestions.length > 0) {
    // For entire book quiz, take 25 randomized questions with shuffled options
    const count = Math.min(25, allBookQuestions.length);
    const shuffled = [...allBookQuestions].sort(() => 0.5 - Math.random()).slice(0, count);
    return shuffled.map(shuffleQuestionOptions);
  }

  // Fallback: return testament questions with shuffled options
  return CORE_QUESTIONS
    .filter((q) => q.categoryId === 'old_testament')
    .slice(0, 10)
    .map(shuffleQuestionOptions);
}

// Helper: Synchronously get questions for a Bible Book (reads from cache if loaded)
export function getQuestionsForBook(bookId: string, chapter?: number): Question[] {
  const normalizedId = bookId.toLowerCase().trim();
  const cached = bookCache.get(normalizedId);

  if (cached && cached.length > 0) {
    if (chapter) {
      const chapterQuestions = cached.filter((q) => q.chapter === chapter);
      if (chapterQuestions.length > 0) {
        return chapterQuestions.map(shuffleQuestionOptions);
      }
    }
    const count = Math.min(25, cached.length);
    const shuffled = [...cached].sort(() => 0.5 - Math.random()).slice(0, count);
    return shuffled.map(shuffleQuestionOptions);
  }

  // Core questions for other books
  const bookQuestions = CORE_QUESTIONS.filter((q) => q.bookId === normalizedId);
  if (bookQuestions.length > 0) {
    return bookQuestions.map(shuffleQuestionOptions);
  }

  // Fallback: return testament questions with shuffled options
  return CORE_QUESTIONS
    .filter((q) => q.categoryId === 'old_testament')
    .slice(0, 10)
    .map(shuffleQuestionOptions);
}

