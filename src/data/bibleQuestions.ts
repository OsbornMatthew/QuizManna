// Utility: Shuffle the 4 options so the answer is never predictably Option A
export function shuffleQuestionOptions(question: Question): Question {
  const indices = [0, 1, 2, 3];
  for (let i = indices.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    const temp = indices[i];
    indices[i] = indices[j];
    indices[j] = temp;
  }

  const newOptions = indices.map((i) => question.options[i]) as [string, string, string, string];
  const newOptionsEn = indices.map((i) => question.optionsEn ? question.optionsEn[i] : question.options[i]) as [string, string, string, string];
  const newCorrectAnswer = indices.indexOf(question.correctAnswer);

  return {
    ...question,
    options: newOptions,
    optionsEn: newOptionsEn,
    correctAnswer: newCorrectAnswer,
    correctAnswerEn: newCorrectAnswer,
  };
}

